export function createTranslator(language: LanguageCode = 'en') {
  return (key: string, vars?: TranslationVars) => {
    const template = TRANSLATIONS[language]?.[key] ?? TRANSLATIONS.en[key] ?? key;
    if (!vars) return template;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
  };
}

type Translator = ReturnType<typeof createTranslator>;

export const categoryLabel = (t: Translator, category: string) => t(`category.${category}`);
export const equipmentLabel = (t: Translator, equipment: string) => t(`equipment.${equipment}`);
export const muscleLabel = (t: Translator, muscle: string) => t(`muscle.${muscle}`);
